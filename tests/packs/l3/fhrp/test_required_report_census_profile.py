"""Static synthetic census registration and unchanged required-report metadata."""
from itertools import permutations

import pytest

from atlas_brain.model import pack_registration as registration
from atlas_brain.packs.l2.etherchannel import build as ec
from atlas_brain.packs.l2.stp import build as stp
from atlas_brain.packs.l3.fhrp import parse_hsrp_census as census
from atlas_brain.packs.l3.fhrp import required_report_census_profile as profile
from atlas_brain.packs.l3.fhrp import required_report_profile as required

CENSUS_OPERATION = "synthetic.hsrp_ipv4_interface_census"
CENSUS_STEP = "l3.fhrp/parse_hsrp_census"


def test_explicit_extension_reuses_original_immutable_specs_and_dispatches_nothing(monkeypatch):
    original = required.declaration()
    original_bytes = registration.compile_packs((original,)).registration_bytes

    def forbid_parse(*_args, **_kwargs):
        pytest.fail("static metadata dispatched the census parser")

    monkeypatch.setattr(census, "parse_capture", forbid_parse)
    monkeypatch.setattr(required, "declaration", lambda: original)
    extended = profile.declaration()
    assert extended.pack == original.pack == "l3.fhrp"
    assert extended.entity_kinds is original.entity_kinds
    assert extended.facts is original.facts and extended.relations is original.relations
    assert all(actual is before for actual, before in zip(extended.steps[:-1], original.steps, strict=True))
    assert all(actual is before for actual, before in zip(extended.operations[:-1], original.operations, strict=True))
    assert extended.steps[-1].row() == {
        "step": CENSUS_STEP, "pack": "l3.fhrp", "kind": "parse_build", "scope": "device",
        "reads": (), "produces": (), "evaluator": "l3.fhrp.parse_hsrp_census",
    }
    assert extended.operations[-1].operation == CENSUS_OPERATION
    assert extended.operations[-1].step == CENSUS_STEP
    assert registration.compile_packs((original,)).registration_bytes == original_bytes


# Literal digests from the source declarations, not generated by the compiler under test.
@pytest.mark.parametrize(
    "peers, original_digest, census_digest",
    [
        ((), "acea0e07643ab18e5783aa0375994d6a07e1b9c75ed0969565d8aa84cb342d1a",
         "b32a233596444b3b9123a224aa613b3c304dfdfe3c9e897d8a0928f0d613c071"),
        ((stp.DECLARATION, ec.DECLARATION), "e714883856add7945d24332c198954364fdced555275d633a659d9b03d2d93cb",
         "23ba8b6955b0a28309b22da3d7239aa60da96820edb85bdbaad6799fd242a975"),
    ],
    ids=("fhrp", "p4"),
)
def test_profile_registration_has_pinned_deterministic_bytes_and_one_new_owner(peers, original_digest, census_digest):
    original = required.declaration()
    extended = profile.declaration()
    before = registration.compile_packs((*peers, original))
    after = registration.compile_packs((*peers, extended))
    assert before.registration_sha256 == original_digest and after.registration_sha256 == census_digest
    for declarations in permutations((*peers, extended)):
        assert registration.compile_packs(declarations) == after
    assert [(binding.operation, binding.step) for binding in after.operations] == [
        *((binding.operation, binding.step) for binding in before.operations),
        (CENSUS_OPERATION, CENSUS_STEP),
    ]
    assert tuple(step for step in after.steps if step.id != CENSUS_STEP) == before.steps


def test_original_and_extended_declarations_cannot_claim_the_pack_together():
    with pytest.raises(ValueError, match="^duplicate_pack$"):
        registration.compile_packs((stp.DECLARATION, ec.DECLARATION, required.declaration(), profile.declaration()))


class ForeignOperation(str):
    def __eq__(self, _other):
        pytest.fail("compared an open operation value")


@pytest.mark.parametrize("kind", ["wrong_operation", "foreign_text"])
def test_changed_operation_is_refused_before_dispatch_or_foreign_comparison(monkeypatch, kind):
    operation = "iosxe.show_standby_brief" if kind == "wrong_operation" else ForeignOperation(CENSUS_OPERATION)
    monkeypatch.setattr(census, "OP", operation)
    with pytest.raises(ValueError, match="^fhrp_census_operation$"):
        profile.declaration()
